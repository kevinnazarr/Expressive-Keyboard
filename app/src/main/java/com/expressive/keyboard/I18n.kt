// I18N: HANYA MENDUKUNG BAHASA INDONESIA (id) & BAHASA INGGRIS (en)
// Secara default sistem akan mendeteksi bahasa Indonesia / Inggris, atau dipilih manual.
// ============================================================================

object I18n {
    var lang by mutableStateOf(systemLang())
        private set

    private fun systemLang(): String =
        if (Locale.getDefault().language in setOf("in", "id")) "id" else "en"

    /** Pengaturan: SYSTEM, id, atau en. */
    fun apply(setting: String) {
        val next = when (setting) {
            "id", "en" -> setting
            else -> systemLang()
        }
        if (next != lang) lang = next
    }

    val isEnglish: Boolean get() = lang == "en"
    val isIndonesian: Boolean get() = lang == "id"
}

fun tr(key: String): String = when {
    I18n.isEnglish -> EN_STRINGS[key] ?: key
    else -> ID_STRINGS[key] ?: EN_STRINGS[key] ?: key
}

fun tr(key: String, vararg args: Any?): String {
    var s = tr(key)
    args.forEachIndexed { i, a -> s = s.replace("{$i}", a.toString()) }
    return s
}

